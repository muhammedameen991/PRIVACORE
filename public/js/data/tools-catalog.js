export function getToolById(id) {
  return TOOLS.find((t) => t.id === id) || null;
}

export function searchTools(query) {
  const q = (query || '').trim().toLowerCase();
  if (!q) return TOOLS;
  return TOOLS.filter((tool) => {
    const hay = [
      tool.name,
      tool.shortDesc,
      tool.category,
      tool.classification,
      ...(tool.keywords || [])
    ]
      .join(' ')
      .toLowerCase();
    return hay.includes(q);
  });
}
